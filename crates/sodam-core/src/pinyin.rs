/// 单个汉字的拼音首字母（小写 ..=z），非基本汉字返回 None。
pub(crate) fn han_initial(ch: char) -> Option<char> {
    let cp = ch as u32;
    if (HAN_START..=HAN_END).contains(&cp) {
        Some(PINYIN_INITIALS[(cp - HAN_START) as usize] as char)
    } else {
        None
    }
}

/// 生成「数字/特殊字符最前，字母与汉字按拼音首字母 A–Z」的排序键。
pub(crate) fn sort_key(text: &str) -> (u8, String, String) {
    let trimmed = text.trim_start();
    let Some(first) = trimmed.chars().next() else {
        return (0, String::new(), String::new());
    };
    let bucket =
        if first.is_ascii_alphabetic() || han_initial(first).is_some() || first.is_alphabetic() {
            1
        } else {
            0
        };
    let mut mapped = String::with_capacity(trimmed.len());
    for ch in trimmed.chars() {
        if let Some(initial) = han_initial(ch) {
            mapped.push(initial);
        } else if ch.is_ascii_alphabetic() {
            mapped.push(ch.to_ascii_lowercase());
        } else {
            for lc in ch.to_lowercase() {
                mapped.push(lc);
            }
        }
    }
    (bucket, mapped, trimmed.to_lowercase())
}
